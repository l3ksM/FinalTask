def intersection(x1: int, y1: int, x2: int, y2: int, x3: int, y3: int, x4: int, y4: int) -> int:
    """
    Вычисляет площадь пересечения двух прямоугольников.
    x1, y1 - левый верхний угол 1-го, x2, y2 - правый нижний 1-го.
    x3, y3 - левый верхний угол 2-го, x4, y4 - правый нижний 2-го.
    """
    # Находим координаты пересечения по осям X и Y
    # По X: максимум из левых границ и минимум из правых
    x_overlap = max(0, min(x2, x4) - max(x1, x3))
    # По Y: максимум из верхних границ и минимум из нижних
    y_overlap = max(0, min(y2, y4) - max(y1, y3))
    
    # Площадь пересечения
    return x_overlap * y_overlap